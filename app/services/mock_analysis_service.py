    @classmethod
    def run_mock_pipeline(
        cls,
        image: ValidatedImage,
        request_id: Optional[str] = None,
        return_heatmap: bool = True,
        verdict_style: str = "canonical",
    ) -> AnalyzeResponse:
        """
        Executes end-to-end mock analysis pipeline producing a complete AnalyzeResponse.
        
        Args:
            image: Verified image metadata.
            request_id: Client correlation ID.
            return_heatmap: Flag to request Grad-CAM evidence.
            verdict_style: 'canonical' (GENUINE/EDITED/SUSPICIOUS) or 'frontend' (REAL/FAKE/SUSPICIOUS).
            
        Returns:
            Validated AnalyzeResponse instance adhering strictly to Phase 1 contracts.
        """
        start_time = time.perf_counter()
        req_id = request_id or f"mock-{uuid.uuid4().hex[:12]}"
        profile = cls.determine_profile(image.filename)

        # 1. OCR Mock
        ocr_res = cls.generate_mock_ocr_result(image, profile=profile)

        # 2. CNN Mock
        cnn_res = cls.generate_mock_cnn_result(
            image, profile=profile, return_heatmap=return_heatmap
        )

        # 3. Semantic Mock
        semantic_res = cls.generate_mock_semantic_result(ocr_res, profile=profile)

        # 4. Stacker Mock
        stacker_res = cls.generate_mock_stacker_result(
            cnn_res, semantic_res, profile=profile
        )

        # Convert CNN suspicious regions to frontend format (with pixel calculations)
        frontend_suspicious_regions: List[SuspiciousRegion] = []
        for reg in cnn_res.suspicious_regions:
            pixel_box = reg.bbox_normalized.to_pixel(image.width, image.height)
            frontend_suspicious_regions.append(
                SuspiciousRegion(
                    label=reg.label,
                    score=reg.score,
                    x=pixel_box.x,
                    y=pixel_box.y,
                    width=pixel_box.width,
                    height=pixel_box.height,
                    box_normalized=reg.bbox_normalized,
                )
            )

        # Map verdicts based on style preference
        if verdict_style.lower() == "frontend":
            if profile == "genuine":
                assigned_verdict = VerdictEnum.REAL
                message = "Analysis completed. Receipt integrity verified; no manipulation detected."
            elif profile == "suspicious":
                assigned_verdict = VerdictEnum.SUSPICIOUS
                message = "Analysis completed with moderate uncertainty due to heavy image compression artifacts."
            else:
                assigned_verdict = VerdictEnum.FAKE
                message = "Analysis completed. Image exhibits localized tampering around amount and font inconsistencies."
        else:
            if profile == "genuine":
                assigned_verdict = VerdictEnum.GENUINE
                message = "Analysis completed. Receipt integrity verified; no manipulation detected."
            elif profile == "suspicious":
                assigned_verdict = VerdictEnum.SUSPICIOUS
                message = "Analysis completed with moderate uncertainty due to heavy image compression artifacts."
            else:
                assigned_verdict = VerdictEnum.EDITED
                message = "Analysis completed. Image exhibits localized tampering around amount and font inconsistencies."

        elapsed_ms = (time.perf_counter() - start_time) * 1000.0
        is_inconclusive = assigned_verdict in [VerdictEnum.INCONCLUSIVE, VerdictEnum.SUSPICIOUS]

        return AnalyzeResponse(
            request_id=req_id,
            verdict=assigned_verdict,
            confidence=None if is_inconclusive else stacker_res.calibrated_confidence,
            decision_score=stacker_res.final_manipulation_probability,
            uncertainty_score=round(1.0 - abs(stacker_res.final_manipulation_probability - 0.5) * 2.0, 4) if is_inconclusive else None,
            manipulation_probability=stacker_res.final_manipulation_probability,
            message=message,
            ocr_data=ocr_res.fields,
            manipulation_analysis=ManipulationAnalysisEvidence(
                detected=len(frontend_suspicious_regions) > 0,
                suspicious_regions=frontend_suspicious_regions,
                heatmap_url=cnn_res.heatmap_relative_path,
            ),
            branch_scores=BranchScores(
                cnn_score=cnn_res.manipulation_probability,
                semantic_score=semantic_res.semantic_manipulation_score,
                stacker_score=stacker_res.final_manipulation_probability,
            ),
            cnn_score=cnn_res.manipulation_probability,
            semantic_score=semantic_res.semantic_manipulation_score,
            stacker_score=stacker_res.final_manipulation_probability,
            reason_codes=semantic_res.reason_codes,
            model_versions=ModelVersionMetadata(
                pipeline_version="v0.1.0-phase2-mock",
                cnn_model_version=cnn_res.model_info.model_version,
                ocr_engine_version=ocr_res.ocr_version,
                semantic_engine_version=semantic_res.model_info.model_version,
                stacker_model_version=stacker_res.stacker_model_version,
            ),
            processing_time_ms=round(elapsed_ms, 2),
            warnings=[cls.MOCK_DISCLAIMER_WARNING],
            pipeline_status="phase2_mock",
            component_status={
                "cnn": "mock",
                "ocr": "mock",
                "semantic": "mock",
                "stacker": "mock",
            },
        )

