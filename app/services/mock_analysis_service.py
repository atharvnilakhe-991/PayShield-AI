    @classmethod
    def determine_profile(cls, filename: Optional[str] = None) -> str:
        """Determines mock profile based on filename keywords for deterministic testing."""
        if not filename:
            return "edited"
        lower = filename.lower()
        if "real" in lower or "genuine" in lower or "authentic" in lower:
            return "genuine"
        if "suspicious" in lower or "uncertain" in lower:
            return "suspicious"
        return "edited"

